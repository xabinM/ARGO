def patch_gps_data(spots_list):
    """기존 스팟 리스트에 GPS 데이터 추가"""
    patched_count = 0
    
    for spot in spots_list:
        location = spot.get("메인장소", "")
        spot_name = spot.get("세부스팟", "")
        
        # GPS가 이미 있는지 확인
        if "위도" in spot and "경도" in spot:
            continue
            
        # 패치 데이터에서 GPS 찾기
        key = (location, spot_name)
        if key in GPS_PATCH_DATA:
            lat, lng = GPS_PATCH_DATA[key]
            spot["위도"] = lat
            spot["경도"] = lng
            patched_count += 1
            print(f"✅ GPS 추가: {location} - {spot_name}")
        else:
            # 기본 서울 좌표 (GPS 없는 스팟들을 위한 폴백)
            spot["위도"] = 37.5665 + (hash(spot_name) % 1000) / 100000
            spot["경도"] = 126.9780 + (hash(spot_name) % 1000) / 100000
            print(f"⚠️ 기본 좌표 사용: {location} - {spot_name}")
            patched_count += 1
    
    print(f"🎯 총 {patched_count}개 스팟에 GPS 추가 완료")
    return spots_list

